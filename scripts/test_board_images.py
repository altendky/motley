"""Test deterministic derivatives and failures that must block freshness checks."""

from contextlib import redirect_stderr, redirect_stdout
import io
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch
import xml.etree.ElementTree as ET

sys.dont_write_bytecode = True
import board_images as images


SVG = '''<svg xmlns="http://www.w3.org/2000/svg" width="10mm" viewBox="0 0 10 10">
<title>SVG Image created as {filename} date {date} </title>
<desc>Image generated by PCBNEW</desc>
<g transform="translate(1 2)"><desc>R1</desc><path d="M 1,2 L 3,4 Z" style="fill:#C83434" /></g>
<path d="M 5,6 L 7,8 Z" style="fill:#D864FF; fill-opacity:0.4000" />
</svg>
'''


class BoardImageTests(unittest.TestCase):
    def setUp(self):
        self.temporary = tempfile.TemporaryDirectory()
        self.addCleanup(self.temporary.cleanup)
        self.root = Path(self.temporary.name)
        (self.root / "mise.toml").write_text('[tools."http:kicad"]\nversion = "1.2.3"\n')
        native = self.root / "hardware/controller"
        native.mkdir(parents=True)
        for board in {v.board for v in images.VIEWS}:
            (native / f"{board}.kicad_pcb").write_text("native board\n")
            (native / f"{board}.kicad_pro").write_text('{"text_variables":{"AUTHOR":"Motley"}}\n')
        self.output = self.root / images.OUTPUT

    def fixture(self, name="old.svg", date="2026-11-14T00:00:00"):
        return SVG.format(filename=name, date=date)

    def test_normalization_removes_time_and_path_without_changing_geometry(self):
        a = images.normalize_svg(self.fixture("/old/path/a.svg"), images.VIEWS[0])
        b = images.normalize_svg(self.fixture("/new/path/b.svg", "1970-01-01T00:00:00")
                                 .replace("\n", "\r\n"), images.VIEWS[0])
        self.assertEqual(a, b)
        self.assertNotIn(b"date ", a)
        self.assertNotIn(b"\r", a)
        self.assertTrue(a.endswith(b"\n"))
        self.assertTrue(all(line == line.rstrip() for line in a.splitlines()))
        before, after = ET.fromstring(self.fixture()), ET.fromstring(a)
        ns = {"s": "http://www.w3.org/2000/svg"}
        self.assertEqual(before.attrib, after.attrib)
        self.assertEqual([p.attrib["d"] for p in before.findall(".//s:path", ns)],
                         [p.attrib["d"] for p in after.findall(".//s:path", ns)])
        self.assertEqual(before.find("s:g", ns).attrib, after.find("s:g", ns).attrib)
        self.assertIn(b"#E9AFA5", a)
        self.assertIn(b"fill:#A8AFBA; fill-opacity:1.0000", a)
        self.assertIn(b"Do not edit this derivative", a)
        self.assertIn(b"<desc>R1</desc>", a)

    def test_bad_or_ambiguous_svg_is_rejected(self):
        for source in ["not SVG", self.fixture().replace("<title>", "<other>"),
                       self.fixture().replace("</desc>", "</desc><desc>duplicate</desc>"),
                       self.fixture().replace("</svg>", "")]:
            with self.subTest(source=source), self.assertRaises(images.ExportError):
                images.normalize_svg(source, images.VIEWS[0])

    def test_check_reports_missing_stale_and_unexpected_without_writing(self):
        content = {"a.svg": b"current\n", "b.svg": b"new\n", "c.svg": b"missing\n"}
        self.output.mkdir(parents=True)
        (self.output / "a.svg").write_bytes(content["a.svg"])
        (self.output / "b.svg").write_bytes(b"old\n")
        (self.output / "obsolete.svg").write_bytes(b"obsolete\n")
        before = {p.name: p.read_bytes() for p in self.output.iterdir()}
        issues = images.synchronize(self.output, content, False)
        self.assertEqual(set(issues), {"stale SVG: b.svg", "missing SVG: c.svg",
                                       "unexpected SVG: obsolete.svg"})
        self.assertEqual(before, {p.name: p.read_bytes() for p in self.output.iterdir()})
        absent = self.root / "absent"
        self.assertEqual(images.synchronize(absent, {"a.svg": b"x"}, False), ["missing SVG: a.svg"])
        self.assertFalse(absent.exists())

    def test_write_then_check_and_repeat_write_preserve_matching_file(self):
        content = {"a.svg": b"generated\n", "b.svg": b"other\n"}
        with redirect_stdout(io.StringIO()):
            self.assertEqual(images.synchronize(self.output, content, True), [])
        path = self.output / "a.svg"
        os.utime(path, ns=(123000000000, 123000000000))
        stamp = path.stat().st_mtime_ns
        with redirect_stdout(io.StringIO()):
            self.assertEqual(images.synchronize(self.output, content, True), [])
        self.assertEqual(path.stat().st_mtime_ns, stamp)
        self.assertEqual(images.synchronize(self.output, content, False), [])

    def test_renderer_pins_version_and_isolates_user_preferences(self):
        work = self.root / "render"
        work.mkdir()
        calls = []

        def exporter(arguments, env):
            calls.append((arguments, env))
            if arguments == ["version"]:
                return "1.2.3"
            target = Path(arguments[arguments.index("--output") + 1])
            source = Path(arguments[3])
            self.assertTrue(source.is_relative_to(work))
            self.assertEqual(source.read_text(), "native board\n")
            self.assertIn("Motley", source.with_suffix(".kicad_pro").read_text())
            source.with_suffix(".kicad_prl").write_text("plotter local settings\n")
            target.write_text(self.fixture(str(target)))
            return "Done"

        with patch.dict(os.environ, {"KICAD_CONFIG_HOME": "/personal", "XDG_CONFIG_HOME": "/personal"}), \
                patch.object(images, "run_kicad", side_effect=exporter):
            rendered = images.render_views(self.root, work)
        self.assertEqual(set(rendered), {v.filename for v in images.VIEWS})
        self.assertEqual(list((self.root / "hardware/controller").glob("*.kicad_prl")), [])
        for args, env in calls:
            self.assertTrue(Path(env["KICAD_CONFIG_HOME"]).is_relative_to(work))
            self.assertTrue(Path(env["XDG_CONFIG_HOME"]).is_relative_to(work))
            if args != ["version"]:
                self.assertEqual(args[args.index("--theme") + 1], "_builtin_default")
                self.assertTrue(Path(args[3]).is_absolute())
        with patch.object(images, "run_kicad", return_value="wrong") as run:
            with self.assertRaisesRegex(images.ExportError, "1.2.3 is required"):
                images.render_views(self.root, work)
            self.assertEqual(run.call_count, 1)

    def test_export_failure_never_writes_partially_generated_results(self):
        self.output.mkdir(parents=True)
        path = self.output / "existing.svg"
        path.write_bytes(b"keep\n")
        error = io.StringIO()
        with patch.object(images, "render_views", side_effect=images.ExportError("renderer failed")), \
                patch.object(images, "synchronize") as sync, redirect_stderr(error):
            self.assertEqual(images.main(["--root", str(self.root), "--write"]), 1)
            sync.assert_not_called()
        self.assertIn("renderer failed", error.getvalue())
        self.assertEqual(path.read_bytes(), b"keep\n")

    def test_cli_mismatch_is_a_failure_with_regeneration_command(self):
        error = io.StringIO()
        with patch.object(images, "render_views", return_value={"missing.svg": b"x"}), \
                redirect_stderr(error):
            self.assertEqual(images.main(["--root", str(self.root), "--check"]), 1)
        self.assertIn("missing SVG", error.getvalue())
        self.assertIn(images.REGENERATE, error.getvalue())
        self.assertFalse(self.output.exists())

    def test_missing_or_failing_kicad_is_not_silently_accepted(self):
        with patch.object(images.subprocess, "run", side_effect=FileNotFoundError):
            with self.assertRaisesRegex(images.ExportError, "unavailable"):
                images.run_kicad(["version"], {})
        with patch.object(images.subprocess, "run", side_effect=subprocess.CalledProcessError(
                7, ["kicad-cli"], output="actual export failure")):
            with self.assertRaisesRegex(images.ExportError, "actual export failure"):
                images.run_kicad(["pcb", "export", "svg"], {})


if __name__ == "__main__":
    unittest.main()
